/* Category folders own classification; project metadata stays in catalog-data.js. */
import fs from 'node:fs';
import path from 'node:path';
import vm from 'node:vm';
import { fileURLToPath, pathToFileURL } from 'node:url';

const repository = fileURLToPath(new URL('../', import.meta.url));
const names = { button: '按钮', background: '背景', label: '标签', text: '文字' };
export function componentStructure(root = repository) {
    const directory = path.join(root, 'single-web/components');
    const categories = [], projects = new Map();
    for (const category of fs.readdirSync(directory, { withFileTypes: true }).filter(item => item.isDirectory() && !item.name.startsWith('.'))) {
        if (!/^[a-z][a-z0-9]*(?:-[a-z0-9]+)*$/.test(category.name)) throw new Error('Invalid category folder: ' + category.name);
        categories.push(category.name);
        for (const project of fs.readdirSync(path.join(directory, category.name), { withFileTypes: true }).filter(item => item.isDirectory() && !item.name.startsWith('.'))) {
            const href = `./single-web/components/${category.name}/${project.name}/index.html`;
            if (!fs.existsSync(path.join(root, href))) throw new Error('Missing project entry: ' + href);
            if (projects.has(project.name)) throw new Error('Duplicate project folder: ' + project.name);
            projects.set(project.name, { category: category.name, href });
        }
    }
    categories.sort((a, b) => a === 'button' ? -1 : b === 'button' ? 1 : a.localeCompare(b));
    return { categories, projects };
}

export function syncCatalog({ root = repository, check = false } = {}) {
    const structure = componentStructure(root), window = {};
    const dataFile = path.join(root, 'assets/catalog-data.js');
    const categoriesFile = path.join(root, 'assets/catalog-categories.js');
    const original = fs.readFileSync(dataFile, 'utf8');
    vm.runInNewContext(original, { window });
    const registered = new Set(window.LibraryCatalog.filter(item => item.section === 'components').map(item => item.id));
    for (const id of structure.projects.keys()) if (!registered.has(id)) throw new Error(`Register ${id} in assets/catalog-data.js before syncing.`);
    const entries = window.LibraryCatalog.map(item => {
        if (item.section !== 'components') return item;
        const project = structure.projects.get(item.id);
        if (!project) throw new Error('Missing component folder: ' + item.id);
        return { ...item, ...project };
    });
    if (fs.existsSync(categoriesFile)) vm.runInNewContext(fs.readFileSync(categoriesFile, 'utf8'), { window });
    const previous = new Map((window.LibraryCategories || []).map(item => [item.id, item.label]));
    const categories = structure.categories.map(id => ({ id, label: previous.get(id) || names[id] || id }));
    if (check) {
        if (JSON.stringify(entries) !== JSON.stringify(window.LibraryCatalog) || JSON.stringify(categories) !== JSON.stringify(window.LibraryCategories)) {
            throw new Error('Catalog paths/categories differ from folders. Run node scripts/sync-catalog.mjs.');
        }
        return structure;
    }
    const data = '/* Project metadata; paths and category IDs follow the component folders. */\nwindow.LibraryCatalog = ' + JSON.stringify(entries, null, 2) + ';\n';
    const categoryData = '/* Generated by scripts/sync-catalog.mjs from single-web/components/. */\nwindow.LibraryCategories = ' + JSON.stringify(categories, null, 2) + ';\n';
    if (original !== data) fs.writeFileSync(dataFile, data);
    if (!fs.existsSync(categoriesFile) || fs.readFileSync(categoriesFile, 'utf8') !== categoryData) fs.writeFileSync(categoriesFile, categoryData);
    return structure;
}
if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
    try {
        const result = syncCatalog({ check: process.argv.includes('--check') });
        console.log(`PASS: ${result.categories.length} category folders; ${result.projects.size} component projects.`);
    } catch (error) { console.error(error.message); process.exitCode = 1; }
}
