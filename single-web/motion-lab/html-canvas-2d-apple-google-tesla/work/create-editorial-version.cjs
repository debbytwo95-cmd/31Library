const fs=require('node:fs');
const latest=fs.readFileSync('outputs/ai-brand-signals.html','utf8');
const initial=fs.readFileSync('outputs/brand-signals-initial.html','utf8');
let html=latest;
let css=initial.match(/<style>([\s\S]*?)<\/style>/)[1];
css=css.replace('aspect-ratio:.68; min-height:490px;','aspect-ratio:3/4; min-height:0;');
css=css.replace('.card { min-height:440px; }','.card { min-height:0; }');
css=css.replace('.card { min-height:510px; aspect-ratio:.72; }','.card { min-height:0; aspect-ratio:3/4; }');
css=css.replace(/  \.apple \{[^\n]+\}/,'  .grok { --bg:linear-gradient(155deg,#111316 0%,#20252b 100%); --fg:#f6f7f8; --sub:#a2aab4; --rule:#454c55; }');
css=css.replace(/  \.google \{[^\n]+\}/,'  .claude { --bg:linear-gradient(165deg,#8a432f 0%,#ba6d4c 58%,#cf8a64 100%); --fg:#fff7ef; --sub:#f3c7a8; --rule:#d49a79; }');
css=css.replace(/  \.tesla \{[^\n]+\}/,'  .chatgpt { --bg:linear-gradient(160deg,#10392f 0%,#145345 60%,#1b6a56 100%); --fg:#effff5; --sub:#add7c8; --rule:#478371; }');
html=html.replace(/<style>[\s\S]*?<\/style>/,'<style>'+css+'</style>');
const intro=initial.slice(initial.indexOf('  <header class="masthead">'),initial.indexOf('  <section class="cards"'));
html=html.replace('  <h1 class="sr-only">Grok / Claude / ChatGPT — Interactive brand signals</h1>\n',intro);
const numbers=['01 / GROK','02 / CLAUDE','03 / GPT'];
let index=0;
html=html.replace(/(<header class="card-top">[\s\S]*?<\/div>)(<\/header>)/g,(_,brand,close)=>brand+'<span class="mono card-number">'+numbers[index++]+'</span>'+close);
const captions=['A different angle.','Room for thought.','Start a conversation.'];
index=0;html=html.replace(/<h2 class="tagline">[\s\S]*?<\/h2>/g,()=>'<h2 class="tagline">'+captions[index++]+'</h2>');
index=0;html=html.replace(/(<span>Reveal the source<\/span>)(<span class="arrow")/g,(_,label,arrow)=>label+'<small>PATH / '+String(++index).padStart(2,'0')+'</small>'+arrow);
let footer=initial.match(/  <footer class="footer">[\s\S]*?<\/footer>/)[0];
footer=footer.replace('60 STRANDS','56 STRANDS');
html=html.replace(/\n<button class="motion" aria-pressed="false">[^<]*<\/button>/,'');
html=html.replace('</main>',footer+'\n</main>');
html=html.replace('<meta name="theme-color" content="#ffffff">','<meta name="theme-color" content="#f4f3ef">');
// Match the first edition's fixed 22 × 24 CSS-pixel header icon, including DPR.
html=html.replace('const w=this.width*.0625,h=this.width*.069,ctx=this.icon.getContext(\'2d\');',"const w=22,h=24,ctx=this.icon.getContext('2d');");
fs.writeFileSync('outputs/ai-brand-signals-editorial.html',html);
console.log('Created outputs/ai-brand-signals-editorial.html ('+Buffer.byteLength(html)+' bytes)');
